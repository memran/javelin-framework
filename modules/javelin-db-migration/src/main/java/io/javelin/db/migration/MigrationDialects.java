package io.javelin.db.migration;

import java.util.Locale;

/** Built-in dialects, selected from the configured JDBC driver or URL. */
public final class MigrationDialects {
    public static final MigrationDialect POSTGRESQL = () -> """
            create table if not exists javelin_migrations (
                id bigint generated by default as identity primary key,
                migration_name varchar(255) not null unique,
                batch integer not null,
                ran_at timestamp not null
            )
            """;

    public static final MigrationDialect MYSQL = () -> """
            create table if not exists javelin_migrations (
                id bigint auto_increment primary key,
                migration_name varchar(191) not null unique,
                batch integer not null,
                ran_at timestamp not null
            )
            """;

    public static final MigrationDialect SQLITE = () -> """
            create table if not exists javelin_migrations (
                id integer primary key autoincrement,
                migration_name varchar(255) not null unique,
                batch integer not null,
                ran_at timestamp not null
            )
            """;

    private MigrationDialects() {
    }

    public static MigrationDialect from(String hint) {
        String value = hint == null ? "" : hint.toLowerCase(Locale.ROOT);
        if (value.contains("mysql") || value.contains("mariadb")) {
            return MYSQL;
        }
        if (value.contains("sqlite")) {
            return SQLITE;
        }
        return POSTGRESQL;
    }
}
